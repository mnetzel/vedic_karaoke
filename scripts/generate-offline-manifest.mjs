import { isUtf8 } from 'node:buffer';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const output = new URL('offline-manifest.js', root);
const digest = (data) => createHash('sha256').update(data).digest('hex');

async function filesIn(directory) {
  const entries = await readdir(new URL(directory, root), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const path = directory + encodeURIComponent(entry.name);
    if (entry.isDirectory()) files.push(...await filesIn(`${path}/`));
    if (entry.isFile()) files.push(path);
  }
  return files;
}

const shell = (await readdir(root, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && /\.(html|css|js|ico|webmanifest)$/i.test(entry.name)
    && entry.name !== 'sw.js' && entry.name !== 'offline-manifest.js')
  .map(({ name }) => encodeURIComponent(name));
const paths = [...shell, ...await filesIn('input/'), ...await filesIn('vendor/')].sort();
const files = {};
for (const path of paths) {
  const raw = await readFile(new URL(path, root));
  const text = /\.(html|css|js|json|md|svg|textgrid|webmanifest|txt|xml)$/i.test(path) && isUtf8(raw);
  const data = text ? Buffer.from(raw.toString('utf8').replace(/\r\n/g, '\n')) : raw;
  files[path] = { bytes: data.length, hash: digest(data), ...(text && { text }) };
}

const total = Object.values(files).reduce((sum, file) => sum + file.bytes, 0);
const worker = await readFile(new URL('sw.js', root), 'utf8');
const version = digest(JSON.stringify(files) + digest(worker.replace(/\r\n/g, '\n')));
const script = `// Generated by scripts/generate-offline-manifest.mjs.\nself.OFFLINE_ASSETS = ${JSON.stringify({ version, total, files }, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== script) {
    console.error('Offline manifest is stale. Run node scripts/generate-offline-manifest.mjs.');
    process.exitCode = 1;
  }
} else {
  await writeFile(output, script);
  console.log(`${fileURLToPath(output)}: ${paths.length} assets, ${(total / 1e6).toFixed(1)} MB`);
}
